import json

def load(i): return json.load(open(f'words{i}.json'))
def save(i, d): json.dump(d, open(f'words{i}.json', 'w'), ensure_ascii=False, indent=1)

def replace_range(words, start_idx, end_idx, new_words):
    return words[:start_idx] + new_words + words[end_idx:]

# ---- video1 ----
w1 = load(1)
for w in w1:
    if w['w'] == 'егэ':
        w['w'] = 'ЕГЭ'
    if w['w'] == 'фипи':
        w['w'] = 'ФИПИ'
# "в одно и тоже время" -- "тоже" (слитно, частица "тоже"="также") не
# согласуется по смыслу; устойчивая фраза "в одно и ТО ЖЕ время" (раздельно,
# местоимение "то" + частица "же") -- та же самая омофонная пара, разница
# только в написании, не в звучании; разбито на два слова в границах
# исходного токена
idx_t = next(i for i,w in enumerate(w1) if w['w']=='тоже')
w1 = replace_range(w1, idx_t, idx_t+1, [
    {'w':'то','t':23.764,'end':23.9},
    {'w':'же','t':23.91,'end':24.024},
])
# CTA: "в" действительно присутствует по передекоду (широкий передекод
# 26.4-28.0с показал отдельный токен ' в' на 26.400, перед "ша" на 26.720)
idx = next(i for i,w in enumerate(w1) if w['w']=='шапки')
w1 = replace_range(w1, idx, idx, [{'w':'в','t':26.40,'end':26.68}])
idx = next(i for i,w in enumerate(w1) if w['w']=='шапки')
w1[idx]['w'] = 'шапке'
save(1, w1)
print('video1 fixed:', len(w1), 'words')

